/**
 * Generate targets/win-host/PrismHost.Core/Channel/Channel.g.cs from the channel
 * schema in packages/core/src/win-channel.ts (built to dist/ first). One
 * source of truth (win-host-spec §2): the C# records, the op-name constants,
 * and the M1 dispatch surface all come from here — never hand-edited.
 *
 * Run: node scripts/generate-win-channel.mjs   (or npm run gen:win-channel)
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const { COMMAND_SCHEMA, HOST_CALLS, SURFACE_EVENT_TYPES } = await import(
  "file://" + join(root, "packages/core/dist/win-channel.js")
);

const CS_TYPE = {
  string: "string",
  "string?": "string?",
  number: "double",
  boolean: "bool",
  json: "System.Text.Json.JsonElement?",
  rect: "ChannelRect",
};

function pascal(op) {
  return op.replace(/[.-](\w)/g, (_, c) => c.toUpperCase()).replace(/^(\w)/, (_, c) => c.toUpperCase());
}

const lines = [];
lines.push("// <auto-generated>");
lines.push("// GENERATED from packages/core/src/win-channel.ts by scripts/generate-win-channel.mjs.");
lines.push("// Do not edit — the schema in core is the single source of truth (win-host-spec §2).");
lines.push("// </auto-generated>");
lines.push("#nullable enable");
lines.push("using System.Text.Json;");
lines.push("using System.Text.Json.Serialization;");
lines.push("");
lines.push("namespace PrismHost.Channel;");
lines.push("");
lines.push("public readonly record struct ChannelRect(");
lines.push("    [property: JsonPropertyName(\"x\")] double X,");
lines.push("    [property: JsonPropertyName(\"y\")] double Y,");
lines.push("    [property: JsonPropertyName(\"w\")] double W,");
lines.push("    [property: JsonPropertyName(\"h\")] double H);");
lines.push("");
lines.push("public static class Ops");
lines.push("{");
for (const c of COMMAND_SCHEMA) lines.push(`    public const string ${pascal(c.op)} = "${c.op}";`);
lines.push("}");
lines.push("");
lines.push("public static class HostCalls");
lines.push("{");
for (const f of HOST_CALLS) lines.push(`    public const string ${pascal(f)} = "${f}";`);
lines.push("}");
lines.push("");
lines.push("public static class SurfaceEvents");
lines.push("{");
for (const t of SURFACE_EVENT_TYPES) lines.push(`    public const string ${pascal(t)} = "${t}";`);
lines.push("}");
lines.push("");
lines.push("/// <summary>One command from core; RequestId is set on request-lane ops.</summary>");
lines.push("public sealed record CommandEnvelope(");
lines.push("    [property: JsonPropertyName(\"op\")] string Op,");
lines.push("    [property: JsonPropertyName(\"requestId\")] double? RequestId = null);");
lines.push("");
for (const c of COMMAND_SCHEMA) {
  const name = pascal(c.op) + "Command";
  // C# records: optional parameters must trail required ones
  const entries = Object.entries(c.fields);
  const ordered = [...entries.filter(([, t]) => t !== "string?" && t !== "json"), ...entries.filter(([, t]) => t === "string?" || t === "json")];
  const props = ordered.map(([f, t]) => {
    const cs = CS_TYPE[t];
    if (!cs) throw new Error(`unknown field type ${t} on ${c.op}.${f}`);
    const opt = t === "string?" || t === "json" ? " = null" : "";
    return `    [property: JsonPropertyName("${f}")] ${cs} ${pascal(f)}${opt}`;
  });
  lines.push(`/// <summary>${c.op}${c.request ? " (request lane — answer via PrismRuntime.resolve)" : ""}${c.m1 ? " [M1]" : " [stub until later milestone]"}</summary>`);
  if (props.length === 0) lines.push(`public sealed record ${name}();`);
  else lines.push(`public sealed record ${name}(\n${props.join(",\n")});`);
  lines.push("");
}
lines.push("public static class ChannelSchema");
lines.push("{");
lines.push("    /// <summary>op → is request-lane (needs a resolve answer).</summary>");
lines.push("    public static readonly System.Collections.Generic.Dictionary<string, bool> RequestLane = new()");
lines.push("    {");
for (const c of COMMAND_SCHEMA) lines.push(`        ["${c.op}"] = ${c.request ? "true" : "false"},`);
lines.push("    };");
lines.push("    /// <summary>ops the M1 host implements; every other op logs + (request lane) resolves with an 'unsupported' error.</summary>");
lines.push("    public static readonly System.Collections.Generic.HashSet<string> M1 = new()");
lines.push("    {");
for (const c of COMMAND_SCHEMA.filter((x) => x.m1)) lines.push(`        "${c.op}",`);
lines.push("    };");
lines.push("}");

const outDir = join(root, "targets/win-host/PrismHost.Core/Channel");
mkdirSync(outDir, { recursive: true });
const out = join(outDir, "Channel.g.cs");
writeFileSync(out, lines.join("\n") + "\n");
console.log(`generated ${out}: ${COMMAND_SCHEMA.length} commands, ${HOST_CALLS.length} host calls, ${SURFACE_EVENT_TYPES.length} surface events`);
